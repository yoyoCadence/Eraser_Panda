#!/usr/bin/env python3
"""Generate advance widths of the standard 14 PDF fonts for WinAnsiEncoding codes 32..255.

Non-embedded standard fonts (Helvetica, Times, Courier) are often written WITHOUT a /Widths array, but we need
widths to keep the following glyphs in place after removing a word, and to compute highlight boxes.
Source: reportlab's bundled Adobe AFM metrics.   Output: src/formats/pdf/data/stdWidths.ts
"""
import os

from reportlab.pdfbase import pdfmetrics

FONTS = ["Helvetica", "Helvetica-Bold", "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic"]
out = ["// Generated by scripts/gen_std_widths.py — do not edit.", "// Widths (1/1000 em) of codes 32..255 in WinAnsiEncoding.", "export const STD_WIDTHS: Record<string, number[]> = {"]
for f in FONTS:
    ws = []
    for code in range(32, 256):
        try:
            ch = bytes([code]).decode("cp1252")
            ws.append(round(pdfmetrics.stringWidth(ch, f, 1000)))
        except UnicodeDecodeError:
            ws.append(0)
    out.append(f"  '{f}': [{','.join(map(str, ws))}],")
out.append("};")
path = os.path.join(os.path.dirname(__file__), "..", "src", "formats", "pdf", "data", "stdWidths.ts")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", path)
